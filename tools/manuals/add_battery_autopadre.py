"""Battery group sizes for the models added after Phase 0: LOW confidence, autopadre.com only.

Same owner decision as add_battery.py (2026-10-14): no OEM document prints BCI groups, so third-party
values are published with `confidence: low` and the "verify on your battery label" disclaimer. There is no
research-note layer here: every record quotes an autopadre.com per-year row from the cached page
(data/cache/web/autopadre/<page>.html). Records for one engine/group/condition merge across consecutive
years. A year with no row stays empty. Tesla has no page (404), so the Model 3 is a gap.
Run last, after each model's builder and add_wipers.py.
"""
import re, sys
from pathlib import Path
import yaml
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))
from autopadre import rows

# slug -> [(cached page, doc title, first year, last year)]
PAGES = {
    "honda/accord": [("honda-accord", "Honda Accord", 2005, 2026)],
    "toyota/camry": [("toyota-camry", "Toyota Camry", 2005, 2026)],
    "toyota/corolla": [("toyota-corolla", "Toyota Corolla", 2005, 2026)],
    "ram/1500": [("dodge-ram-1500", "Dodge Ram 1500", 2005, 2010), ("ram-1500", "Ram 1500", 2011, 2026)],
}

def group_din(code):
    m = re.match(r"^(H\d) \((\w+)\)$", code)
    return (m.group(2), m.group(1)) if m else (code, None)

def condition(trim):
    """'L4/2.5L; Hybrid; Flooded; ...' -> 'Hybrid'; older rows are 'Standard', 'Opt', 'Cold Gas Standard, Climate'."""
    if re.search(r"\bhybrid\b", trim, re.I):
        return "Hybrid"
    if re.search(r"\b(dsl|diesel)\b", trim, re.I):
        return "diesel"
    if re.search(r"\bcold\b", trim, re.I):
        return "cold climate"
    if re.search(r"\bopt\b", trim, re.I):
        return "optional"
    return None

for slug, pages in PAGES.items():
    path = ROOT / "data/manuals" / f"{slug}.yaml"
    data = yaml.safe_load(path.read_text())
    data["records"] = [r for r in data["records"] if not (r["field"] == "battery" and r.get("confidence") == "low")]
    for page, title, y0, y1 in pages:
        ref = f"autopadre_{page.replace('-', '_')}"
        data["sources"][ref] = {"doc": f"AutoPadre: {title} battery size", "url": f"https://www.autopadre.com/battery-size/{page}",
                                "type": "third_party_reference", "accessed": "2026-11-01"}
        found = {}  # (displacement, group, din, condition) -> {year: quote}
        for r in rows(ROOT / "data/cache/web/autopadre" / f"{page}.html"):
            if not y0 <= r["year"] <= y1:
                continue
            d = re.search(r"/(\d\.\d)L", r["trim"])
            group, din = group_din(r["code"])
            found.setdefault((float(d.group(1)) if d else None, group, din, condition(r["trim"])), {}).setdefault(r["year"], r["quote"][:200])
        for (displ, group, din, cond), years in sorted(found.items(), key=lambda kv: (min(kv[1]), kv[0][1], kv[0][0] or 0)):
            ys = sorted(years)
            spans, start = [], ys[0]
            for a, b in zip(ys, ys[1:] + [None]):
                if b != a + 1:
                    spans.append((start, a)); start = b
            for a, b in spans:
                rec = {"field": "battery", "years": [a, b]}
                if displ is not None:
                    rec["displacement_l"] = displ
                rec["engine"] = f"{displ}L" if displ is not None else "all engines"
                if cond:
                    rec["condition"] = cond
                rec["group"] = group
                if din:
                    rec["din"] = din
                rec["confidence"] = "low"
                rec["src"] = [{"ref": ref, "quote": years[y]} for y in sorted({a, b})]
                data["records"].append(rec)
    with open(path, "w") as fh:
        fh.write("# Generated by tools/manuals (see its README). Battery records with `confidence: low` are third-party only.\n")
        yaml.safe_dump(data, fh, sort_keys=False, allow_unicode=True, width=120)
    print(f"{slug:18s} battery records: {sum(r['field'] == 'battery' for r in data['records'])}")
