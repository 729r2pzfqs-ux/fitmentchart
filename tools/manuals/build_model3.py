"""Tesla Model 3 (2017-2026) tires. No oil (EV), no towing, wiper or battery records.

tesla.com answers 403 to the pipeline identity and to WebFetch, so no owner's manual could be
read and every value here comes from a fetched non-Tesla document:
- tirepressure.com year pages (third_party_reference), one per model year
- Goodyear vehicle pages (aftermarket_fitment): 2024-26 Performance staggered sizes
- NHTSA NCAP test report: 2018 Long Range RWD tire data

Dropped from tirepressure.com's 2017 page: 245/35R21 and 245/45R19 (on no other year, and absent
from Goodyear's and tiresize.com's 2017 lists), and the Performance trim, 235/35R20 row included
(EPA lists only "Model 3 Long Range" for 2017).

Towing is left empty: no Tesla document could be read, and secondary sources conflict.
Fetch the pages into data/cache/web/ and the NCAP PDF into data/cache/manuals/tesla-model-3/ first.
"""
import html, re, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))
from mkyaml import DOCS, cite, dump
from tirepressure import rows as tp_rows

ACCESSED = "2026-11-01"
WEB = ROOT / "data/cache/web"
OUT = ROOT / "data/manuals/tesla/model-3.yaml"
DROP_2017 = {"245/35R21", "245/45R19", "235/35R20"}

def trim_lists(path):
    """{size: [trims]} from the saved page's <li> items; tirepressure.rows() flattens these."""
    body = path.read_text(errors="replace")
    body = body[body.find("Tire Inflation Chart"):]
    body = body[:body.find("</table>")]
    out = {}
    for tr in re.findall(r"<tr>(.*?)</tr>", body, re.S):
        size = re.search(r"\d{3}/\d{2}Z?R\d{2}", tr)
        if size:
            out[size.group(0)] = [html.unescape(t).strip() for t in re.findall(r"<li>(.*?)</li>", tr, re.S)]
    return out

DOCS["ncap2018"] = {"pdf": str(ROOT / "data/cache/manuals/tesla-model-3/v10383R002.pdf"),
                    "doc": "NHTSA NCAP Frontal Barrier Impact Test, 2018 Tesla Model 3 Long Range RWD (NCAP-KAR-18-020)",
                    "url": "https://nrd-static.nhtsa.dot.gov/reports/vehdb/v10000/v10300/v10383R002.pdf",
                    "type": "third_party_reference", "accessed": ACCESSED}
ncap = cite("ncap2018", 9, r"Recommended Tire Size P235/40R19 P235/40R19", ["235/40R19"])

R = []
for y in range(2017, 2027):
    ref = f"tp{y}"
    DOCS[ref] = {"doc": f"TirePressure.com: {y} Tesla Model 3 Tire Pressure",
                 "url": f"https://tirepressure.com/{y}-tesla-model-3-tire-pressure",
                 "type": "third_party_reference", "accessed": ACCESSED}
    rows = tp_rows(WEB / f"tp_model3_{y}.html")
    lists = trim_lists(WEB / f"tp_model3_{y}.html")
    if not rows:
        raise SystemExit(f"no tire rows parsed for {y}")
    for row in rows:
        trims = lists[row["size"]]
        if y == 2017:
            if row["size"] in DROP_2017:
                continue
            trims = [t for t in trims if t != "Long Range Performance"]
        src = [{"ref": ref, "quote": row["text"][:200]}]
        if y == 2018 and row["size"] == "235/40R19":
            src.append(ncap)
        R.append({"field": "tires", "years": [y, y], "trim": ", ".join(trims), "size": row["size"], "src": src})

for y in (2024, 2025, 2026):
    ref = f"gy{y}"
    url = f"https://www.goodyear.com/en-us/vehicles/Tesla/Model-3/{y}/Performance"
    DOCS[ref] = {"doc": f"Goodyear: {y} Tesla Model 3 Performance Tires", "url": url,
                 "type": "aftermarket_fitment", "accessed": ACCESSED}
    page = (WEB / f"goodyear_m3_{y}p.html").read_text(errors="replace")
    quote = "Front: 235/35R20, Rear: 275/30R20"
    if quote not in page or f"Find {y} Tesla Model 3 Performance Tires" not in page:
        raise SystemExit(f"Goodyear {y}: expected text not on saved page")
    for pos, size in (("front", "235/35R20"), ("rear", "275/30R20")):
        R.append({"field": "tires", "years": [y, y], "trim": "Performance", "size": size, "position": pos,
                  "src": [{"ref": ref, "quote": quote}]})

OUT.parent.mkdir(parents=True, exist_ok=True)
dump(str(OUT), "tesla/model-3", R)
text = OUT.read_text().split("\n", 1)[1]
OUT.write_text("# Generated by tools/manuals/build_model3.py; web quotes are verbatim from saved pages, the PDF quote is verified by cite().\n" + text)
